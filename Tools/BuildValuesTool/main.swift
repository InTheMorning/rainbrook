// musicindex ADR 0083 R-VERSION-1: writes the git revision and the build time of the app as Swift source.
// Usage: BuildValuesTool <package directory> <output file>
// The rules are the rules of the Rust crate `musicindex-build-info` (R-VERSION-8 item 1):
// - The environment value comes first: RAINBROOK_GIT_REVISION and RAINBROOK_BUILT_AT.
// - Else the git revision is the short hash of HEAD, with `-dirty` when a tracked file has changes.
// - Else the build time is the time now in UTC.
import Foundation

let arguments = CommandLine.arguments
guard arguments.count == 3 else {
    FileHandle.standardError.write(Data("usage: BuildValuesTool <package directory> <output file>\n".utf8))
    exit(2)
}
let packageDirectory = arguments[1]
let outputPath = arguments[2]
let environment = ProcessInfo.processInfo.environment

/// The output of one Git command with no space at the start and the end, or nil when Git fails.
func git(_ gitArguments: [String]) -> String? {
    let process = Process()
    process.executableURL = URL(fileURLWithPath: "/usr/bin/env")
    // `--no-optional-locks`: the status command does not write the index.
    process.arguments = ["git", "--no-optional-locks", "-C", packageDirectory] + gitArguments
    let output = Pipe()
    process.standardOutput = output
    process.standardError = FileHandle.nullDevice
    do {
        try process.run()
    } catch {
        return nil
    }
    let data = output.fileHandleForReading.readDataToEndOfFile()
    process.waitUntilExit()
    guard process.terminationStatus == 0 else { return nil }
    return String(data: data, encoding: .utf8)?.trimmingCharacters(in: .whitespacesAndNewlines)
}

func fromEnvironment(_ name: String) -> String? {
    guard let value = environment[name], !value.isEmpty else { return nil }
    return value
}

func gitRevision() -> String? {
    guard let hash = git(["rev-parse", "--short", "HEAD"]), !hash.isEmpty else { return nil }
    let changes = git(["status", "--porcelain", "--untracked-files=no"]) ?? ""
    return changes.isEmpty ? hash : "\(hash)-dirty"
}

func now() -> String {
    let formatter = ISO8601DateFormatter()
    formatter.timeZone = TimeZone(identifier: "UTC")
    formatter.formatOptions = [.withInternetDateTime]
    return formatter.string(from: Date())
}

/// A Swift string literal, or `nil`.
func literal(_ value: String?) -> String {
    guard let value else { return "nil" }
    let escaped = value.replacingOccurrences(of: "\\", with: "\\\\").replacingOccurrences(of: "\"", with: "\\\"")
    return "\"\(escaped)\""
}

let revision = fromEnvironment("RAINBROOK_GIT_REVISION") ?? gitRevision()
let builtAt = fromEnvironment("RAINBROOK_BUILT_AT") ?? now()
let source = """
// Generated by BuildValuesTool at each build. Do not edit. musicindex ADR 0083 R-VERSION-1.
public enum GeneratedBuildValues {
    public static let gitRevision: String? = \(literal(revision))
    public static let builtAt: String? = \(literal(builtAt))
}

"""
do {
    try source.write(toFile: outputPath, atomically: true, encoding: .utf8)
} catch {
    FileHandle.standardError.write(Data("BuildValuesTool: cannot write \(outputPath): \(error)\n".utf8))
    exit(1)
}
